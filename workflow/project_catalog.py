def normalize_catalog_key(val: str) -> str:
    """Normalize Persian/Arabic letters, digits, and whitespace for resilient matching."""
    cleaned = re.sub(r"\s+", " ", str(val or "").strip())
    return cleaned.translate(_FA_AR_TRANS)


def _load_catalog():
    projects = []
    by_norm_name = {}
    by_code = {}
    sites_by_value = {}
    banks_by_value = {}
    branches_by_key = {}
    branches_by_norm_name = {}

    for row in csv.DictReader(io.StringIO(_RAW_CSV)):
        code = normalize_catalog_key(row["کد پروژه"])
        name = re.sub(r"\s+", " ", row["نام پروژه"].strip())
        raw_site = re.sub(r"\s+", " ", row["نام سایت"].strip())
        canonical_site = _SITE_TO_CANONICAL.get(raw_site, raw_site)
        raw_bank = re.sub(r"\s+", " ", row["بانک"].strip())
        bank_code, canonical_bank = _BANK_MAP[raw_bank]
        branch_code = normalize_catalog_key(row["کدشعبه"])
        branch_name = re.sub(r"\s+", " ", row["نام شعبه"].strip())

        entry = {
            "code": code,
            "name": name,
            "site": canonical_site,
            "site_csv": raw_site,
            "bank_code": bank_code,
            "bank_name": canonical_bank,
            "bank_csv": raw_bank,
            "branch_code": branch_code,
            "branch_name": branch_name,
            "project_type": row["نوع پروژه"].strip(),
            "city": row["شهر"].strip(),
        }
        projects.append(entry)
        by_norm_name[normalize_catalog_key(name)] = entry
        by_code[code] = entry

        if canonical_site not in sites_by_value:
            sites_by_value[canonical_site] = {
                "value": canonical_site,
                "csv_label": raw_site,
                "city": entry["city"],
            }
        if canonical_bank not in banks_by_value:
            banks_by_value[canonical_bank] = {
                "value": canonical_bank,
                "csv_label": raw_bank,
                "bank_code": bank_code,
            }

        br_key = (branch_name, canonical_bank, branch_code)
        if br_key not in branches_by_key:
            branches_by_key[br_key] = {
                "branch_name": branch_name,
                "branch_code": branch_code,
                "bank_name": canonical_bank,
                "bank_code": bank_code,
            }
        branches_by_norm_name.setdefault(normalize_catalog_key(branch_name), branch_name)

    return (
        projects,
        by_norm_name,
        by_code,
        list(sites_by_value.values()),
        list(banks_by_value.values()),
        sorted(branches_by_key.values(), key=lambda b: (b["bank_name"], b["branch_name"])),
        branches_by_norm_name,
    )


