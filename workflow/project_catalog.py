def get_catalog_project_mapping(project_name: str):
    """Return a lightweight mapping object compatible with ProjectBankMapping consumers."""
    entry = _PROJECTS_BY_NORM_NAME.get(normalize_catalog_key(project_name))
    if not entry:
        return None
    bank_code = entry["bank_code"]
    bank_name = entry["bank_name"]
    return SimpleNamespace(
        project_code=entry["code"],
        project_name=entry["name"],
        bank_code=bank_code,
        branch_code=entry["branch_code"],
        branch_name=entry["branch_name"],
        site=entry["site"],
        get_bank_code_display=lambda bn=bank_name: bn,
    )


def resolve_catalog_field(field_name: str, value: str) -> tuple[bool, str]:
    """Validate and canonicalize a single catalog-controlled field."""
    norm = normalize_catalog_key(value)
    if not norm:
        return True, ""

    if field_name == "site":
        canonical = _SITES_BY_NORM.get(norm)
        return (True, canonical) if canonical else (False, value)
    if field_name == "project":
        entry = _PROJECTS_BY_NORM_NAME.get(norm)
        return (True, entry["name"]) if entry else (False, value)
    if field_name == "project_code":
        entry = _PROJECTS_BY_CODE.get(norm)
        return (True, entry["code"]) if entry else (False, value)
    if field_name == "bank_name":
        canonical = _BANKS_BY_NORM.get(norm)
        return (True, canonical) if canonical else (False, value)
    if field_name == "bank_branch":
        canonical = _BRANCHES_BY_NORM_NAME.get(norm)
        if canonical:
            return True, canonical
        # Also allow picking/typing a branch code from the catalog
        for br in CATALOG_BRANCHES:
            if br["branch_code"] == norm:
                return True, br["branch_name"]
        return False, value
    return True, value


def validate_catalog_updates(dossier, parsed_updates: dict) -> Optional[str]:
    """Ensure modified catalog fields stay strictly within the 96-project approved list.

    Untouched legacy values on existing dossiers remain undisturbed when unrelated fields change.
    """
    for field_name in ("site", "project", "project_code", "bank_name", "bank_branch"):
        if field_name not in parsed_updates:
            continue
        new_val = (parsed_updates[field_name] or "").strip()
        old_val = (getattr(dossier, field_name, "") or "").strip()
        if normalize_catalog_key(new_val) == normalize_catalog_key(old_val):
            continue
        ok, canonical = resolve_catalog_field(field_name, new_val)
        if not ok:
            label = _FIELD_LABELS.get(field_name, field_name)
            return f"مقدار «{new_val}» برای فیلد «{label}» مجاز نیست. لطفاً فقط از لیست مصوب انتخاب نمایید."
        parsed_updates[field_name] = canonical
    return None
