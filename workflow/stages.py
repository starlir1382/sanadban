def map_old_to_new_stage(old_stage: int) -> int:
    """Safely converts an old stage number (0-21) to the new stage number."""
    return OLD_TO_NEW_STAGE_MAP.get(old_stage, old_stage)


def map_new_to_old_stage(new_stage: int) -> int:
    """Safely converts a new stage number back to the old stage number (0-21)."""
    return NEW_TO_OLD_STAGE_MAP.get(new_stage, new_stage)


def convert_allowed_stages_string(allowed_stages_str: str, forward: bool = True) -> str:
    """
    Converts comma-separated allowed stages string between old and new systems.
    Example forward: "0,1,2,10" -> "1,2,9"
    Special value "all" remains "all".
    """
    if allowed_stages_str is None:
        return "all"

    trimmed = allowed_stages_str.strip()
    if trimmed == "all":
        return "all"
    if not trimmed:
        return ""

    mapping = OLD_TO_NEW_STAGE_MAP if forward else NEW_TO_OLD_STAGE_MAP
    result_stages = set()

    for part in trimmed.split(","):
        part = part.strip()
        if part.isdigit():
            num = int(part)
            if num in mapping:
                result_stages.add(mapping[num])
            elif 1 <= num <= 22:
                result_stages.add(num)

    if not result_stages:
        return ""

    return ",".join(str(s) for s in sorted(result_stages))
